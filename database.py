"""PostgreSQL storage. Every query uses a pooled connection and bound parameters."""
import contextvars
import os
from contextlib import contextmanager

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

SCHEMA = """
CREATE TABLE IF NOT EXISTS characters (
 scope TEXT PRIMARY KEY, name TEXT NOT NULL DEFAULT '小惡魔',
 personality TEXT NOT NULL DEFAULT '有點驕傲、調皮、愛吐槽，但尊重他人',
 image_url TEXT NOT NULL DEFAULT '', mood TEXT NOT NULL DEFAULT '普通'
);
CREATE TABLE IF NOT EXISTS profiles (
 scope TEXT NOT NULL, user_id TEXT NOT NULL,
 exp INTEGER NOT NULL DEFAULT 0, affection INTEGER NOT NULL DEFAULT 0,
 last_checkin TEXT NOT NULL DEFAULT '', last_reward_at TIMESTAMPTZ,
 PRIMARY KEY(scope,user_id)
);
CREATE TABLE IF NOT EXISTS inventory (
 scope TEXT NOT NULL, user_id TEXT NOT NULL, item TEXT NOT NULL,
 quantity INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(scope,user_id,item)
);
CREATE TABLE IF NOT EXISTS memories (
 scope TEXT NOT NULL, user_id TEXT NOT NULL,
 summary TEXT NOT NULL DEFAULT '', last_id BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(scope,user_id)
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 scope TEXT NOT NULL, user_id TEXT NOT NULL, role TEXT NOT NULL,
 content TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS messages_owner_idx ON messages(scope,user_id,id DESC);
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS last_reward_at TIMESTAMPTZ;
"""

class Result:
    def __init__(self, rows, rowcount):
        self.rows = rows
        self.rowcount = rowcount

    def fetchone(self):
        return self.rows[0] if self.rows else None

    def fetchall(self):
        return self.rows


class Database:
    def __init__(self, dsn):
        # Supabase Session Pooler is compatible with prepared statements.
        self.pool = ConnectionPool(conninfo=dsn, min_size=1, max_size=5,
                                   kwargs={"row_factory": dict_row, "autocommit": True},
                                   open=False)
        self.current = contextvars.ContextVar('db_connection', default=None)

    def open(self):
        self.pool.open(wait=True, timeout=30)
        with self.pool.connection() as conn:
            for statement in SCHEMA.split(';'):
                if statement.strip():
                    conn.execute(statement)

    def close(self):
        self.pool.close()

    def execute(self, sql, params=()):
        sql = sql.replace('?', '%s').replace('MIN(100,', 'LEAST(100,')
        sql = sql.replace('INSERT OR IGNORE INTO characters(scope) VALUES(%s)',
                          'INSERT INTO characters(scope) VALUES(%s) ON CONFLICT DO NOTHING')
        sql = sql.replace('INSERT OR IGNORE INTO profiles(scope,user_id) VALUES(%s,%s)',
                          'INSERT INTO profiles(scope,user_id) VALUES(%s,%s) ON CONFLICT DO NOTHING')
        conn = self.current.get()
        if conn is not None:
            cur = conn.execute(sql, params)
            return Result(cur.fetchall() if cur.description else [], cur.rowcount)
        with self.pool.connection() as conn:
            cur = conn.execute(sql, params)
            return Result(cur.fetchall() if cur.description else [], cur.rowcount)

    @contextmanager
    def transaction(self):
        with self.pool.connection() as conn:
            with conn.transaction():
                token = self.current.set(conn)
                try:
                    yield
                finally:
                    self.current.reset(token)


def connect():
    dsn = os.getenv('DATABASE_URL')
    if not dsn:
        raise RuntimeError('請在 Render Environment 設定 DATABASE_URL（Supabase Session Pooler URI）')
    if 'sslmode=' not in dsn:
        dsn += ('&' if '?' in dsn else '?') + 'sslmode=require'
    database = Database(dsn)
    database.open()
    return database
